import asyncio
import json
import logging
import time
from typing import Dict, Any, Optional, Set
import httpx
import websockets
from ..services.trade_service import trade_service, HEADERS_BASE

logger = logging.getLogger("user_data_stream")


class UserDataStreamManager:
    """
    Manages Binance User Data Stream lifecycle (listenKey creation, keep-alive, and WebSocket stream relay).
    Also relays simulated paper trading account updates for a unified real-time experience.
    """

    def __init__(self):
        self._active_listeners: Set[websockets.WebSocketServerProtocol] = set()
        self._connected_clients: Set[Any] = set()  # FastAPI WebSockets
        self._listen_keys: Dict[str, Dict[str, Any]] = {}  # key: f"{market}_{mode}_{api_key[-8:]}" -> {listenKey, task, ws_task}
        self._lock = asyncio.Lock()

    def _get_stream_key(self, market: str, mode: str, api_key: str) -> str:
        return f"{market.lower().strip()}_{mode.lower().strip()}_{api_key[-8:] if api_key else 'sim'}"

    async def register_client(self, client_ws: Any, market: str, mode: str, api_key: str = "", api_secret: str = ""):
        """Register a browser WebSocket client and ensure upstream Binance stream is running if live."""
        mode_clean, key_clean, secret_clean = trade_service._resolve_credentials(mode, api_key, api_secret)
        stream_key = self._get_stream_key(market, mode_clean, key_clean)

        async with self._lock:
            self._connected_clients.add((client_ws, stream_key))

        logger.info(f"Client registered for User Data Stream ({stream_key}). Total clients: {len(self._connected_clients)}")

        # If live/testnet with valid API key, ensure upstream Binance User Data WebSocket is running
        if mode_clean == "live" or (mode_clean == "demo" and not trade_service._server_credentials.get("useSimulatedDemo", True)):
            if key_clean:
                await self._ensure_upstream_stream(market, mode_clean, key_clean)

    async def unregister_client(self, client_ws: Any):
        """Unregister a browser WebSocket client."""
        async with self._lock:
            to_remove = [item for item in self._connected_clients if item[0] == client_ws]
            for item in to_remove:
                self._connected_clients.remove(item)

        logger.info(f"Client unregistered from User Data Stream. Remaining clients: {len(self._connected_clients)}")

    async def broadcast_event(self, stream_key: str, event_data: Dict[str, Any]):
        """Broadcast an account/order event to all browser clients matching the stream key."""
        dead_clients = []
        payload_str = json.dumps(event_data)

        for client_ws, s_key in list(self._connected_clients):
            if s_key == stream_key or stream_key == "all":
                try:
                    await client_ws.send_text(payload_str)
                except Exception:
                    dead_clients.append(client_ws)

        if dead_clients:
            async with self._lock:
                self._connected_clients = {item for item in self._connected_clients if item[0] not in dead_clients}

    async def broadcast_paper_event(self, event_type: str, data: Dict[str, Any]):
        """Broadcast an event generated by simulated paper trading."""
        payload = {
            "source": "SIMULATED_PAPER",
            "type": event_type,
            "timestamp": int(time.time() * 1000),
            **data
        }
        await self.broadcast_event("futures_demo_sim", payload)
        await self.broadcast_event("spot_demo_sim", payload)

    async def _ensure_upstream_stream(self, market: str, mode: str, api_key: str):
        """Ensure the Binance listenKey and WebSocket connection are active."""
        stream_key = self._get_stream_key(market, mode, api_key)
        if stream_key in self._listen_keys and self._listen_keys[stream_key].get("active"):
            return

        listen_key = await self._obtain_listen_key(market, mode, api_key)
        if not listen_key:
            logger.warning(f"Could not obtain listenKey from Binance for {stream_key}")
            return

        # Start keep-alive loop (Binance listenKey expires in 60 min, must ping every 30 min)
        keepalive_task = asyncio.create_task(
            self._listen_key_keepalive_loop(market, mode, api_key, listen_key, stream_key)
        )

        # Start upstream Binance WebSocket reader
        ws_task = asyncio.create_task(
            self._upstream_ws_loop(market, mode, listen_key, stream_key)
        )

        self._listen_keys[stream_key] = {
            "listenKey": listen_key,
            "keepalive_task": keepalive_task,
            "ws_task": ws_task,
            "active": True,
            "created_at": time.time()
        }
        logger.info(f"Binance User Data Stream initialized successfully for {stream_key}")

    async def _obtain_listen_key(self, market: str, mode: str, api_key: str) -> Optional[str]:
        """Request a new listenKey from Binance."""
        market_clean = market.lower().strip()
        mode_clean = mode.lower().strip()

        if market_clean == "futures":
            base_url = "https://fapi.binance.com" if mode_clean == "live" else "https://testnet.binancefuture.com"
            path = "/fapi/v1/listenKey"
        else:
            base_url = "https://api.binance.com" if mode_clean == "live" else "https://testnet.binance.vision"
            path = "/api/v3/userDataStream"

        url = f"{base_url}{path}"
        headers = {**HEADERS_BASE, "X-MBX-APIKEY": api_key}
        timeout = httpx.Timeout(10.0, connect=5.0)

        try:
            async with httpx.AsyncClient(headers=headers, timeout=timeout) as client:
                resp = await client.post(url)
                if resp.status_code == 200:
                    data = resp.json()
                    return data.get("listenKey")
                else:
                    logger.error(f"Failed to get listenKey: HTTP {resp.status_code} {resp.text}")
        except Exception as exc:
            logger.error(f"Exception obtaining listenKey: {exc}")

        return None

    async def _keep_alive_listen_key(self, market: str, mode: str, api_key: str, listen_key: str) -> bool:
        """Send keepalive ping for listenKey."""
        market_clean = market.lower().strip()
        mode_clean = mode.lower().strip()

        if market_clean == "futures":
            base_url = "https://fapi.binance.com" if mode_clean == "live" else "https://testnet.binancefuture.com"
            path = "/fapi/v1/listenKey"
        else:
            base_url = "https://api.binance.com" if mode_clean == "live" else "https://testnet.binance.vision"
            path = f"/api/v3/userDataStream?listenKey={listen_key}"

        url = f"{base_url}{path}"
        headers = {**HEADERS_BASE, "X-MBX-APIKEY": api_key}
        timeout = httpx.Timeout(10.0, connect=5.0)

        try:
            async with httpx.AsyncClient(headers=headers, timeout=timeout) as client:
                resp = await client.put(url)
                return resp.status_code == 200
        except Exception as exc:
            logger.warning(f"Error keeping listenKey alive: {exc}")
            return False

    async def _listen_key_keepalive_loop(self, market: str, mode: str, api_key: str, listen_key: str, stream_key: str):
        """Keep-alive loop running every 25 minutes."""
        while True:
            await asyncio.sleep(25 * 60)  # 25 minutes
            if stream_key not in self._listen_keys or not self._listen_keys[stream_key].get("active"):
                break
            success = await self._keep_alive_listen_key(market, mode, api_key, listen_key)
            if success:
                logger.info(f"Extended listenKey keep-alive for {stream_key}")
            else:
                logger.warning(f"Failed to extend listenKey keep-alive for {stream_key}")

    async def _upstream_ws_loop(self, market: str, mode: str, listen_key: str, stream_key: str):
        """Connect to Binance User Data WebSocket stream and forward parsed messages."""
        market_clean = market.lower().strip()
        mode_clean = mode.lower().strip()

        if market_clean == "futures":
            ws_base = "wss://fstream.binance.com/ws" if mode_clean == "live" else "wss://stream.binancefuture.com/ws"
        else:
            ws_base = "wss://stream.binance.com:9443/ws" if mode_clean == "live" else "wss://testnet.binance.vision/ws"

        ws_url = f"{ws_base}/{listen_key}"
        reconnect_delay = 2.0

        while stream_key in self._listen_keys and self._listen_keys[stream_key].get("active"):
            try:
                logger.info(f"Connecting to Binance User Data Stream: {ws_url[:40]}...")
                async with websockets.connect(
                    ws_url,
                    ping_interval=20,
                    ping_timeout=20,
                    open_timeout=10,
                    close_timeout=5
                ) as b_ws:
                    logger.info(f"Connected to Binance User Data Stream ({stream_key})!")
                    reconnect_delay = 2.0

                    # Notify clients connected
                    await self.broadcast_event(stream_key, {
                        "type": "USER_STREAM_STATUS",
                        "status": "CONNECTED",
                        "timestamp": int(time.time() * 1000)
                    })

                    while stream_key in self._listen_keys and self._listen_keys[stream_key].get("active"):
                        raw_msg = await b_ws.recv()
                        if not raw_msg:
                            continue
                        try:
                            msg = json.loads(raw_msg)
                        except Exception:
                            continue

                        event_type = msg.get("e")

                        # Handle Futures events
                        if event_type == "ACCOUNT_UPDATE":
                            # Invalidate REST cache so any subsequent call gets 100% fresh data
                            trade_service._positions_cache.clear()
                            account_data = msg.get("a", {})
                            positions_raw = account_data.get("P", [])
                            balances_raw = account_data.get("B", [])

                            # Format positions update
                            parsed_positions = []
                            for p in positions_raw:
                                amt = float(p.get("pa", 0))
                                parsed_positions.append({
                                    "symbol": p.get("s"),
                                    "side": "LONG" if amt > 0 else "SHORT",
                                    "positionAmt": amt,
                                    "entryPrice": float(p.get("ep", 0)),
                                    "unrealizedProfit": float(p.get("up", 0)),
                                    "marginType": p.get("mt", "cross"),
                                    "is_simulated": False
                                })

                            await self.broadcast_event(stream_key, {
                                "type": "ACCOUNT_UPDATE",
                                "eventTime": msg.get("E"),
                                "reason": account_data.get("m"),
                                "positions": parsed_positions,
                                "balances": balances_raw,
                                "raw": msg
                            })

                        elif event_type == "ORDER_TRADE_UPDATE":
                            # Invalidate orders & positions cache
                            trade_service._orders_cache.clear()
                            trade_service._positions_cache.clear()
                            order_info = msg.get("o", {})

                            parsed_order = {
                                "symbol": order_info.get("s"),
                                "clientOrderId": order_info.get("c"),
                                "side": order_info.get("S"),
                                "type": order_info.get("o"),
                                "orderId": order_info.get("i"),
                                "origQty": float(order_info.get("q", 0)),
                                "price": float(order_info.get("p", 0)),
                                "stopPrice": float(order_info.get("sp", 0)),
                                "executionType": order_info.get("x"),
                                "status": order_info.get("X"),
                                "executedQty": float(order_info.get("z", 0)),
                                "lastFilledPrice": float(order_info.get("L", 0)),
                                "commission": float(order_info.get("n", 0)),
                                "time": order_info.get("T", int(time.time() * 1000)),
                                "is_simulated": False
                            }

                            await self.broadcast_event(stream_key, {
                                "type": "ORDER_TRADE_UPDATE",
                                "eventTime": msg.get("E"),
                                "order": parsed_order,
                                "raw": msg
                            })

                        elif event_type == "MARGIN_CALL":
                            await self.broadcast_event(stream_key, {
                                "type": "MARGIN_CALL",
                                "raw": msg
                            })

                        elif event_type in ("outboundAccountPosition", "executionReport"):
                            # Spot events
                            trade_service._orders_cache.clear()
                            await self.broadcast_event(stream_key, {
                                "type": event_type,
                                "raw": msg
                            })

            except asyncio.CancelledError:
                break
            except Exception as exc:
                logger.warning(f"Binance User Data WS error for {stream_key}: {exc}. Reconnecting in {reconnect_delay}s...")
                await self.broadcast_event(stream_key, {
                    "type": "USER_STREAM_STATUS",
                    "status": "RECONNECTING",
                    "message": str(exc),
                    "timestamp": int(time.time() * 1000)
                })
                await asyncio.sleep(reconnect_delay)
                reconnect_delay = min(reconnect_delay * 1.5, 30.0)


user_data_stream_manager = UserDataStreamManager()
